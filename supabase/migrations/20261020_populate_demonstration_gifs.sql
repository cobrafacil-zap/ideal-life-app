DECLARE
  total INT;
  com_demo INT;
BEGIN
  SELECT COUNT(*) INTO total FROM public.exercises WHERE user_id IS NULL;
  SELECT COUNT(*) INTO com_demo FROM public.exercises
   WHERE user_id IS NULL AND demonstration_url IS NOT NULL;
